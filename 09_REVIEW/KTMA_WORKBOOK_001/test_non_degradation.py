"""
Executable pytest test suite for the Non-Degradation Acceptance Contract.

Tests verify that the generated candidate workbook:
1. Contains all required PH1 worksheets and additive sheets.
2. Contains all required columns with correct data types.
3. Meets minimum row counts.
4. Has structured tables and auto-filters enabled.
5. Preserves accounting data integrity (UF/CLP values, D = E + F).
6. Maintains audit traceability and evidence JSON linkages.
"""

from __future__ import annotations

import json
from pathlib import Path
import openpyxl
import pytest

from kt_movemacc.non_degradation_contract import get_contract, NonDegradationContract


@pytest.fixture(scope="module")
def contract() -> NonDegradationContract:
    return get_contract()


@pytest.fixture(scope="module")
def workbook_path() -> Path:
    # Path to candidate workbook generated by canonical_workbook.py
    path = Path("OUTPUT/2026.08/KTMA_FINANCIAL_WORKBOOK_2026.08.xlsx")
    if not path.exists():
        # Fallback to review path if needed
        path = Path("09_REVIEW/KTMA_WORKBOOK_001/CANDIDATE_KTMA_FINANCIAL_WORKBOOK_2026.08.xlsx")
    if not path.exists():
        pytest.skip(f"Workbook not found at {path}. Run canonical_workbook.py first.")
    return path


@pytest.fixture(scope="module")
def wb(workbook_path: Path):
    return openpyxl.load_workbook(workbook_path, data_only=True)


def test_required_sheets_presence(wb, contract):
    """Verify all required PH1 sheets and additive sheets are present."""
    sheetnames = wb.sheetnames
    
    # Required baseline sheets
    for s_contract in contract.required_sheets:
        assert s_contract.name in sheetnames, f"Required sheet missing: {s_contract.name}"
        
    # Additive sheets
    for s_contract in contract.additive_sheets:
        assert s_contract.name in sheetnames, f"Additive sheet missing: {s_contract.name}"


def test_sheet_columns_and_schema(wb, contract):
    """Verify all required columns are present in each worksheet."""
    all_sheet_contracts = list(contract.required_sheets) + list(contract.additive_sheets)
    
    for s_contract in all_sheet_contracts:
        ws = wb[s_contract.name]
        headers = [cell.value for cell in ws[1] if cell.value is not None]
        
        # Check required columns
        for req_col in s_contract.required_columns:
            assert req_col in headers, f"Sheet '{s_contract.name}' missing required column: '{req_col}'. Found: {headers}"


def test_sheet_row_counts(wb, contract):
    """Verify worksheets meet minimum row requirements."""
    all_sheet_contracts = list(contract.required_sheets) + list(contract.additive_sheets)
    
    for s_contract in all_sheet_contracts:
        ws = wb[s_contract.name]
        data_rows = ws.max_row - 1  # Exclude header
        assert data_rows >= s_contract.min_rows, f"Sheet '{s_contract.name}' has {data_rows} rows, expected at least {s_contract.min_rows}"


def test_structured_tables_and_filters(wb, contract):
    """Verify structured tables and auto-filters are present where required."""
    for s_contract in contract.additive_sheets:
        ws = wb[s_contract.name]
        if s_contract.must_have_table:
            assert len(ws.tables) > 0, f"Additive sheet '{s_contract.name}' must have an Excel structured table"


def test_accounting_data_non_degradation(wb):
    """Verify accounting data is non-zero and properly formatted."""
    ws = wb["03_Consolidated_PH1"]
    
    # Check that total values are present and numeric
    total_val_col = None
    headers = [cell.value for cell in ws[1]]
    for idx, h in enumerate(headers, 1):
        if h == "Total Value UF":
            total_val_col = idx
            break
            
    assert total_val_col is not None, "Column 'Total Value UF' not found in consolidated sheet"
    
    non_zero_count = 0
    for r in range(2, ws.max_row + 1):
        val = ws.cell(row=r, column=total_val_col).value
        if val is not None and isinstance(val, (int, float)) and val != 0.0:
            non_zero_count += 1
            
    assert non_zero_count > 100, f"Consolidated sheet has only {non_zero_count} non-zero total value rows, expected > 100"


def test_evidence_traceability_linkages(wb):
    """Verify Evidence JSON or source row linkages are present."""
    ws = wb["03_Consolidated_PH1"]
    headers = [cell.value for cell in ws[1]]
    
    has_evidence_col = "Evidence JSON" in headers or "Evidence" in headers
    assert has_evidence_col, "Consolidated sheet must contain audit evidence column"


def test_fm_mapping_allocation_integrity(wb):
    """Verify Funding Memo mapping allocation sheet is populated and correct."""
    ws = wb["04_FM_Mapping"]
    assert ws.max_row > 50, "FM Mapping sheet must contain allocation rules"
    
    # Check assigned UF column exists
    headers = [cell.value for cell in ws[1]]
    assert "Assigned UF" in headers, "FM Mapping sheet missing 'Assigned UF'"
